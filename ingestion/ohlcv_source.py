"""
Pluggable OHLCV ingestion. All sources return the same schema so downstream
feature/label code never needs to know which vendor a bar came from:

    date, open, high, low, close, adj_close, volume

`adj_close` must already be split/dividend adjusted (back-adjusted so past
prices are comparable to today's). `close` stays unadjusted for reference.
Phase 1 ships two sources:

  SampleCSVSource — reads the offline synthetic dataset generated by
                    scripts/generate_sample_data.py. No network required;
                    this is the default so the whole pipeline runs offline.

  YFinanceSource   — live data via the `yfinance` package. Optional import:
                    only fails if you actually try to use it without the
                    package installed / network available.

Both honor the same interface, so swapping to a paid vendor (Polygon, IEX,
Tiingo, etc.) later is a one-file change.
"""

from __future__ import annotations

import os
from abc import ABC, abstractmethod
from datetime import date

import pandas as pd

OHLCV_COLUMNS = ["date", "open", "high", "low", "close", "adj_close", "volume"]

SAMPLE_DATA_DIR = os.path.join(os.path.dirname(__file__), "..", "data", "market", "sample")


class OHLCVSource(ABC):
    @abstractmethod
    def get_bars(self, symbol: str, start: date, end: date) -> pd.DataFrame:
        """Returns a DataFrame with OHLCV_COLUMNS, sorted ascending by date."""
        raise NotImplementedError

    def get_bars_multi(self, symbols: list[str], start: date, end: date) -> dict[str, pd.DataFrame]:
        return {s: self.get_bars(s, start, end) for s in symbols}


class SampleCSVSource(OHLCVSource):
    def __init__(self, data_dir: str = SAMPLE_DATA_DIR):
        self.data_dir = data_dir

    def get_bars(self, symbol: str, start: date, end: date) -> pd.DataFrame:
        path = os.path.join(self.data_dir, f"{symbol}.csv")
        if not os.path.exists(path):
            raise FileNotFoundError(
                f"No sample data for {symbol} at {path}. "
                f"Run scripts/generate_sample_data.py first."
            )
        df = pd.read_csv(path, parse_dates=["date"])
        df = df[(df["date"].dt.date >= start) & (df["date"].dt.date <= end)]
        df = df.sort_values("date").reset_index(drop=True)
        missing = set(OHLCV_COLUMNS) - set(df.columns)
        if missing:
            raise ValueError(f"{path} is missing columns: {missing}")
        return df[OHLCV_COLUMNS]


class YFinanceSource(OHLCVSource):
    """Live data via yfinance. Import is deferred so Phase 1 works fully
    offline unless this class is actually instantiated and used."""

    def __init__(self):
        try:
            import yfinance  # noqa: F401
        except ImportError as exc:
            raise ImportError(
                "yfinance is not installed. `pip install yfinance` to use YFinanceSource, "
                "or use SampleCSVSource for offline development."
            ) from exc

    def get_bars(self, symbol: str, start: date, end: date) -> pd.DataFrame:
        import yfinance as yf

        raw = yf.download(
            symbol, start=start.isoformat(), end=end.isoformat(),
            auto_adjust=False, progress=False,
        )
        if raw.empty:
            return pd.DataFrame(columns=OHLCV_COLUMNS)
        raw = raw.reset_index()
        if isinstance(raw.columns, pd.MultiIndex):
            raw.columns = [c[0] for c in raw.columns]
        df = pd.DataFrame({
            "date": pd.to_datetime(raw["Date"]),
            "open": raw["Open"],
            "high": raw["High"],
            "low": raw["Low"],
            "close": raw["Close"],
            "adj_close": raw["Adj Close"],
            "volume": raw["Volume"].astype("int64"),
        })
        return df.sort_values("date").reset_index(drop=True)
