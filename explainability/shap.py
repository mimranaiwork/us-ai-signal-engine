"""
Model explainability (spec section 47). Uses XGBoost's native
`pred_contribs=True` (SHAP values via the exact tree-SHAP algorithm built
into the library) rather than the separate `shap` package — one fewer heavy
dependency for the same numbers, since XGBoost's implementation *is* the
same TreeSHAP algorithm the `shap` package would call for a tree model.

Reasons/risks are generated by mapping the top contributing *known* feature
columns through a fixed human-readable phrase table — never by asking an
LLM to invent an explanation from the numbers, per the spec's explicit
instruction. A feature with no entry in REASON_PHRASES is skipped rather
than described with a fabricated sentence.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import xgboost as xgb

# feature_column -> (phrase if this feature is pushing the score UP, phrase if pushing DOWN)
REASON_PHRASES: dict[str, tuple[str, str]] = {
    "price_vs_sma50": ("Price above 50-day average", "Price below 50-day average"),
    "price_vs_sma200": ("Price above 200-day average", "Price below 200-day average"),
    "price_vs_sma20": ("Price above 20-day average", "Price below 20-day average"),
    "rsi_14": ("Positive RSI momentum", "Weak RSI momentum"),
    "macd_histogram": ("Positive MACD momentum", "Negative MACD momentum"),
    "roc_10": ("Positive 10-day rate of change", "Negative 10-day rate of change"),
    "sma50_slope": ("50-day average trending up", "50-day average trending down"),
    "sma200_slope": ("200-day average trending up", "200-day average trending down"),
    "volume_ratio": ("Elevated relative volume", "Below-average relative volume"),
    "relative_strength_vs_SPY_21d": ("Outperforming SPY over the last month", "Underperforming SPY over the last month"),
    "relative_strength_vs_QQQ_21d": ("Outperforming QQQ over the last month", "Underperforming QQQ over the last month"),
    "relative_strength_vs_SPY_5d": ("Outperforming SPY this week", "Underperforming SPY this week"),
    "volatility_20d": ("Elevated volatility", "Low volatility"),
    "bollinger_band_width": ("Wide Bollinger Bands (high volatility)", "Narrow Bollinger Bands (low volatility)"),
    "atr_percent": ("Elevated average true range", "Contained average true range"),
    "mfi_14": ("Strong money flow", "Weak money flow"),
    "stochastic_k": ("Elevated stochastic oscillator", "Depressed stochastic oscillator"),
}

# Features whose *high* values always mean elevated risk, regardless of sign of contribution to score.
RISK_FEATURES: dict[str, str] = {
    "volatility_20d": "Elevated volatility",
    "atr_percent": "Elevated average true range",
    "bollinger_band_width": "Wide trading range (high volatility)",
}


def shap_contributions(model: xgb.XGBClassifier, X_row: pd.DataFrame, class_index: int) -> pd.Series:
    """Returns per-feature SHAP contribution to the given class's logit for one row."""
    booster = model.get_booster()
    dmatrix = xgb.DMatrix(X_row)
    contribs = booster.predict(dmatrix, pred_contribs=True)  # (n_rows, n_classes, n_features+1) for multi:softprob
    contribs = np.asarray(contribs)
    if contribs.ndim == 3:
        row_contribs = contribs[0, class_index, :-1]  # drop bias term (last column)
    else:
        row_contribs = contribs[0, :-1]
    return pd.Series(row_contribs, index=X_row.columns)


def top_reasons_and_risks(
    model: xgb.XGBClassifier, X_row: pd.DataFrame, buy_class_index: int, top_n: int = 5,
) -> tuple[list[str], list[str]]:
    contributions = shap_contributions(model, X_row, buy_class_index)
    ranked = contributions.reindex(contributions.abs().sort_values(ascending=False).index)

    reasons = []
    for feature, contribution in ranked.items():
        if feature not in REASON_PHRASES or len(reasons) >= top_n:
            continue
        up_phrase, down_phrase = REASON_PHRASES[feature]
        reasons.append(up_phrase if contribution > 0 else down_phrase)

    risks = []
    for feature, phrase in RISK_FEATURES.items():
        if feature in X_row.columns:
            value = X_row.iloc[0][feature]
            # A feature-specific "is this elevated" check would need per-feature
            # historical percentiles (Phase 4 backtesting territory); Phase 3
            # flags it as a risk whenever it's among the row's largest
            # magnitude SHAP contributors, which is what's available now.
            if feature in contributions.abs().sort_values(ascending=False).index[:5]:
                risks.append(phrase)

    return reasons, risks
